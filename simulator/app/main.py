import asyncio
import time

from fastapi import FastAPI
from pydantic import BaseModel, Field

from app.state import TelemetryEvent, calculate_p95, state, utc_now

app = FastAPI(title="Checkout Incident Simulator", version="0.2.0")


class CheckoutRequest(BaseModel):
    customer_id: str = Field(min_length=1, max_length=100)
    item_count: int = Field(default=1, ge=1, le=20)


class HighLatencyScenarioRequest(BaseModel):
    latency_seconds: float = Field(default=4.0, gt=0, le=60)


async def slow_payment_dependency(delay_ms: int) -> None:
    """Simulate a real downstream payment operation that takes time to complete."""
    await asyncio.sleep(delay_ms / 1000)


@app.get("/health")
async def health() -> dict[str, str]:
    return {"status": "ok"}


@app.post("/api/checkout")
async def checkout(request: CheckoutRequest) -> dict[str, str | int | float]:
    request_started = time.perf_counter()

    dependency_started = time.perf_counter()
    await slow_payment_dependency(state.processing_delay_ms)
    dependency_duration_ms = (time.perf_counter() - dependency_started) * 1000

    duration_ms = (time.perf_counter() - request_started) * 1000

    state.events.append(
        TelemetryEvent(
            latency_ms=duration_ms,
            status_code=200,
            timestamp=utc_now(),
            endpoint="/api/checkout",
            dependency="payment-service",
            dependency_duration_ms=dependency_duration_ms,
        )
    )

    return {
        "status": "accepted",
        "customer_id": request.customer_id,
        "item_count": request.item_count,
        "duration_ms": round(duration_ms, 2),
        "dependency_duration_ms": round(dependency_duration_ms, 2),
    }


@app.post("/api/scenarios/high-latency/seed")
async def configure_high_latency(
    request: HighLatencyScenarioRequest,
) -> dict[str, str | int | float]:
    """Configure the real checkout path to use a deliberately slow dependency."""
    state.reset()

    delay_ms = int(round(request.latency_seconds * 1000))
    state.processing_delay_ms = delay_ms

    state.changes.append(
        {
            "timestamp": utc_now(),
            "type": "configuration",
            "field": "CHECKOUT_PROCESSING_DELAY_MS",
            "previous_value_ms": 50,
            "new_value_ms": delay_ms,
            "summary": (
                "CHECKOUT_PROCESSING_DELAY_MS changed "
                f"from 50 to {delay_ms}."
            ),
        }
    )

    return {
        "scenario": "checkout-high-latency-v1",
        "configured_latency_seconds": request.latency_seconds,
        "latency_ms": delay_ms,
        "message": "Scenario configured. Telemetry will be generated by real checkout requests.",
    }


@app.get("/api/telemetry/checkout")
async def checkout_telemetry() -> dict[str, object]:
    latencies = [event.latency_ms for event in state.events]
    errors = [event for event in state.events if event.status_code >= 500]
    request_count = len(state.events)

    return {
        "request_count": request_count,
        "error_count": len(errors),
        "error_rate_percent": (
            (len(errors) / request_count) * 100 if request_count else 0.0
        ),
        "average_latency_ms": (
            sum(latencies) / request_count if request_count else 0.0
        ),
        "p95_latency_ms": calculate_p95(latencies),
        "events": [event.__dict__ for event in state.events[-25:]],
    }


@app.get("/api/changes")
async def recent_changes() -> dict[str, object]:
    return {"changes": state.changes[-10:]}
